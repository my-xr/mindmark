const fs = require('fs');
const path = require('path');
const root = process.cwd();
const read = (f) => fs.readFileSync(path.join(root, f), 'utf8');
const write = (f, s) => fs.writeFileSync(path.join(root, f), s, { encoding: 'utf8' });

// Enrich student score report DTO with fields already needed by the frontend.
{
  const file = 'apps/mindmark-server/src/main/java/com/mindmark/server/modules/score/dto/ScoreReportResponse.java';
  let s = read(file);
  s = s.replace(
`public record ScoreReportResponse(
    String id,
    String examId,
    String examTitle,
    BigDecimal score,
    Integer rank,
    List<String> weakKnowledgePoints,
    String feedback,
    OffsetDateTime publishedAt
) {`,
`public record ScoreReportResponse(
    String id,
    String examId,
    String examTitle,
    String courseName,
    String studentId,
    String studentName,
    String className,
    BigDecimal totalScore,
    BigDecimal score,
    Integer rank,
    List<String> weakKnowledgePoints,
    String feedback,
    OffsetDateTime publishedAt
) {`
  );
  write(file, s);
}

{
  const file = 'apps/mindmark-server/src/main/java/com/mindmark/server/modules/score/service/ScoreReportMapper.java';
  let s = read(file);
  s = s.replace('import java.util.List;\n', 'import java.util.List;\n');
  s = s.replace(
`    public ScoreReportResponse toResponse(ScoreReportEntity report) {
        return new ScoreReportResponse(
            report.getId(),
            report.getExam().getId(),
            report.getExamTitle(),
            report.getScore(),
            report.getRankNo(),
            readKnowledgePoints(report.getWeakKnowledgePointsJson()),
            report.getFeedback(),
            report.getPublishedAt()
        );
    }`,
`    public ScoreReportResponse toResponse(ScoreReportEntity report) {
        return new ScoreReportResponse(
            report.getId(),
            report.getExam().getId(),
            report.getExamTitle(),
            report.getExam().getPaper().getCourseName(),
            report.getStudentId(),
            report.getStudentName(),
            className(report.getExam().getClassIds()),
            report.getExam().getTotalScore(),
            report.getScore(),
            report.getRankNo(),
            readKnowledgePoints(report.getWeakKnowledgePointsJson()),
            report.getFeedback(),
            report.getPublishedAt()
        );
    }

    private String className(List<String> classIds) {
        return classIds == null || classIds.isEmpty() ? "-" : String.join("、", classIds);
    }`
  );
  write(file, s);
}

{
  const file = 'apps/mindmark-server/src/main/java/com/mindmark/server/modules/score/repository/ScoreReportRepository.java';
  let s = read(file);
  s = s.replaceAll('@EntityGraph(attributePaths = {"exam", "answerSheet"})', '@EntityGraph(attributePaths = {"exam", "exam.paper", "exam.classIds", "answerSheet"})');
  write(file, s);
}

// Localize score feedback generated by backend.
{
  const file = 'apps/mindmark-server/src/main/java/com/mindmark/server/modules/score/service/ScoreService.java';
  let s = read(file);
  s = s.replace('return "Overall performance is stable. Keep practicing.";', 'return "整体表现稳定，建议保持当前练习节奏。";');
  s = s.replace('return "Focus on weak knowledge points: " + String.join(", ", weakPoints) + ".";', 'return "建议重点复习薄弱知识点：" + String.join("、", weakPoints) + "。";');
  write(file, s);
}

