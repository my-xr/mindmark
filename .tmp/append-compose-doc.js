const fs = require('fs');
const path = 'docs/21_考试闭环缺口分析与三轮收敛计划.md';
let text = fs.readFileSync(path, 'utf8');
const section = `

### 20.11 随机组卷与智能体组卷闭环

本轮针对“试卷与组卷”补齐真实教师出卷场景，避免教师在 30-50 道题、多个知识点和多个难度层级中完全手工挑题。

#### 已完成能力

- 支持默认 100 分组卷模板：
  - 单选：20 道 × 1 分 = 20 分；
  - 多选：10 道 × 2 分 = 20 分；
  - 判断：10 道 × 1 分 = 10 分；
  - 填空：10 道 × 1 分 = 10 分；
  - 简答：4 道 × 5 分 = 20 分；
  - 编程：2 道 × 10 分 = 20 分。
- 支持教师按题型配置题量、单题分值、难度范围、知识点约束，并可选择“替换当前试题”或“追加到当前试题”。
- 随机组卷：后端事务内从同课程、ACTIVE 状态题库中随机抽题，排除已选题和本次重复题，库存不足时返回中文可理解提示。
- 智能组卷：当前采用“智能规则引擎版组卷智能体”，在满足教师规则的前提下按难度与知识点桶均衡抽题，减少单一知识点或单一难度集中出现的问题。
- 前端“组卷助手”接入真实接口，默认给出 100 分模板，支持一键恢复模板、展开/收起规则、随机组卷、智能组卷，并在组卷后自动刷新试卷列表、当前试卷题目和可选题目池分页。
- OpenAPI 已补充：
  - \`POST /api/v1/papers/{paperId}/compose/random\`
  - \`POST /api/v1/papers/{paperId}/compose/agent\`
  - \`PaperComposeRequest / PaperComposeResultResponse\` 等契约。

#### 企业级边界

- AI/智能体不直接写库；所有组卷结果都必须经过后端校验后写入，校验包括课程边界、题目状态、题型、难度、知识点、去重、目标总分与题库库存。
- 组卷规则总分必须等于目标分值，避免生成“看似 100 分但实际不是 100 分”的试卷。
- 题库不足不会静默降级或生成假数据，而是明确提示缺口题型、需要数量与可用数量。

#### 后续增强建议

- 在题库规模足够后，将智能组卷从“规则引擎版”增强为“LangGraph 计划生成 + 后端强校验执行”：LLM 只输出组卷计划 JSON，例如各题型数量、知识点覆盖比例、难度比例与命题意图；最终选题、去重、计分和写库仍由后端确定性执行。
- 为组卷结果增加“覆盖度报告”：题型分布、难度分布、知识点覆盖、分值占比，便于教师在发布考试前快速复核试卷质量。
- 增加组卷策略模板：期中、期末、章节测验、补考、练习卷，并允许教师按课程保存常用模板。
`;
if (!text.includes('### 20.11 随机组卷与智能体组卷闭环')) {
  text = text.replace(/\s*$/, '') + section + '\n';
}
